#!/usr/bin/env node
// Exports the creature's pixel art (src/pet/sprites.js) to a C header for the
// Nudgling Desk (ESP32 + ST7735), so the desk creature is the same art:
//   hardware/nudgling-desk/sprites.h
// Frames: 5 poses x 2 frames x 4 evolution stages, 24x24 cells, palette
// indices (0 = transparent); palettes per stage in RGB565.
//   node scripts/desk-sprites.mjs
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildFrame, paletteFor, SIZE } from '../src/pet/sprites.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const POSES = [['idle', [0.1, 3.9]], ['talk', [0.0, 0.25]], ['cheer', [0.0, 0.22]], ['sleep', [0.1, 0.8]], ['worry', [0.1, 0.6]]];
const KEYS = ['', 'o', 'w', 'k', 'm', 'p', 'y', 'z', 'g', 'b', 'l', 'd']; // index -> palette key
const rgb565 = (hex) => { const n = parseInt(hex.slice(1), 16); const r = n >> 16, g = (n >> 8) & 255, b = n & 255; return ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3); };

const frames = [];
for (let stage = 1; stage <= 4; stage++) for (const [state, ts] of POSES) for (const t of ts) {
  const f = buildFrame({ state, stage, t });
  frames.push(f.pixels.flat().map((k) => Math.max(0, KEYS.indexOf(k))));
}
const palettes = [1, 2, 3, 4].map((s) => KEYS.map((k) => (k ? rgb565(paletteFor(s)[k]) : 0)));

const hex = (n) => `0x${n.toString(16).padStart(2, '0')}`;
const out = `// Generated by scripts/desk-sprites.mjs from src/pet/sprites.js. Do not edit.
#pragma once
#include <pgmspace.h>
#define SPRITE_SIZE ${SIZE}
#define POSE_IDLE 0
#define POSE_TALK 1
#define POSE_CHEER 2
#define POSE_SLEEP 3
#define POSE_WORRY 4
// frame index = ((stage-1) * 5 + pose) * 2 + n
static const uint8_t SPRITES[${frames.length}][${SIZE * SIZE}] PROGMEM = {
${frames.map((f) => `  {${f.map(hex).join(',')}}`).join(',\n')}
};
static const uint16_t PALETTES[4][${KEYS.length}] PROGMEM = {
${palettes.map((p) => `  {${p.map((n) => `0x${n.toString(16).padStart(4, '0')}`).join(',')}}`).join(',\n')}
};
`;
const file = path.join(root, 'hardware', 'nudgling-desk', 'sprites.h');
writeFileSync(file, out);
console.log(`${file}: ${frames.length} frames, ${Math.round(out.length / 1024)} KB source`);
